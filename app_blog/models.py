from django.db import models
from django.core.validators import RegexValidator

# Common validator to enforce lowercase, alphanumeric, and hyphens only
slug_validator = RegexValidator(
    regex=r'^[a-z0-9]+(?:-[a-z0-9]+)*$',
    message="Slug must be composed of lowercase alphanumeric characters and hyphens only, starting and ending with a letter or number."
)

class GlobalSlug(models.Model):
    slug = models.SlugField(
        max_length=255, 
        unique=True, 
        primary_key=True,
        validators=[slug_validator],
        help_text="Globally unique lowercase URL path."
    )
    page = models.OneToOneField('Page', on_delete=models.CASCADE, null=True, blank=True, related_name='global_slug')
    category = models.OneToOneField('Category', on_delete=models.CASCADE, null=True, blank=True, related_name='global_slug')
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        verbose_name = "Global Slug"
        verbose_name_plural = "Global Slugs"

    def __str__(self):
        if self.page:
            return f"{self.slug} (Page)"
        elif self.category:
            return f"{self.slug} (Category)"
        return self.slug


class Category(models.Model):
    parent = models.ForeignKey(
        'self',
        on_delete=models.CASCADE,
        null=True,
        blank=True,
        related_name='subcategories',
        help_text="Self-referencing foreign key to define category hierarchy."
    )
    name = models.CharField(max_length=255)
    short_description = models.TextField(blank=True)
    description = models.TextField(blank=True)
    image = models.URLField(max_length=500, blank=True)
    icon = models.CharField(max_length=100, blank=True)

    class Meta:
        verbose_name_plural = "Categories"
        ordering = ['name']

    def __str__(self):
        if self.parent:
            return f"{self.parent} > {self.name}"
        return self.name


class Page(models.Model):
    category = models.ForeignKey(
        Category,
        on_delete=models.PROTECT,
        related_name='pages',
        help_text="Prevent category deletion if any active CMS pages exist."
    )
    title = models.CharField(max_length=255)
    # MySQL JSON datatype maps directly via Django JSONField
    json_data = models.JSONField(
        help_text="Dynamic block structure payload generated by Angular workspace."
    )
    compiled_html = models.TextField(
        help_text="Compiled static body HTML string for high-speed public render delivery."
    )
    user_view_count = models.PositiveIntegerField(
        default=0,
        help_text="Read-only counter increments tracked by view counts detail routing actions."
    )
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['-created_at']

    def __str__(self):
        return self.title


class PageSEOMeta(models.Model):
    page = models.OneToOneField(
        Page,
        on_delete=models.CASCADE,
        related_name='seo_meta',
        help_text="Associated metadata details representing 1-to-1 relationship cascading on page deletion."
    )
    meta_title = models.CharField(max_length=255)
    meta_description = models.TextField(blank=True)
    meta_keywords = models.CharField(max_length=500, blank=True)
    canonical_url = models.URLField(max_length=500, blank=True)
    robots_meta = models.CharField(max_length=100, default='index, follow')

    # Facebook Open Graph attributes
    og_title = models.CharField(max_length=255, blank=True)
    og_description = models.TextField(blank=True)
    og_image = models.URLField(max_length=500, blank=True)

    # Twitter Card attributes
    twitter_title = models.CharField(max_length=255, blank=True)
    twitter_description = models.TextField(blank=True)
    twitter_image = models.URLField(max_length=500, blank=True)

    # Focus keywords and structured metadata schema
    focus_keyword = models.CharField(max_length=255, blank=True)
    schema_json = models.JSONField(
        default=dict,
        blank=True,
        help_text="Enforced JSON-LD structured schema metadata."
    )

    class Meta:
        verbose_name = "Page SEO Meta"
        verbose_name_plural = "Pages SEO Meta"

    def __str__(self):
        return f"SEO Settings - {self.page.title}"


class Comment(models.Model):
    page = models.ForeignKey(
        Page,
        on_delete=models.CASCADE,
        related_name='comments',
        help_text="Cascade comment deletions when parent page is deleted."
    )
    user_name = models.CharField(max_length=100)
    comment_text = models.TextField()
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-created_at']

    def __str__(self):
        return f"Comment by {self.user_name} on {self.page.title}"


class MediaGallery(models.Model):
    image = models.ImageField(upload_to='gallery/')
    file_name = models.CharField(max_length=255, blank=True)
    uploaded_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        verbose_name = "Media Gallery Asset"
        verbose_name_plural = "Media Gallery Assets"
        ordering = ['-uploaded_at']

    def __str__(self):
        return self.file_name or (self.image.name if self.image else "No File")
